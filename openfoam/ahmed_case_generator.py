"""
openfoam/ahmed_case_generator.py

Generates complete OpenFOAM simpleFoam cases for Ahmed body geometries.

Takes geometry parameters from ParaKoop inverse design output and writes:
  case_dir/
    0/             → U, p, nut, k, omega
    constant/      → polyMesh/blockMeshDict, transportProperties, turbulenceProperties
    system/        → controlDict, fvSolution, fvSchemes, decomposeParDict

Solver: simpleFoam  (steady incompressible RANS, k-ω SST)
Reference: Lienhart et al. DGLR/SAE-Paper 2000-01-0484 — standard Ahmed body protocol
           Wind tunnel speed U∞ = 40 m/s, Re ≈ 2.8×10⁶ based on body length

Ahmed body coordinate system (metres):
  x  : streamwise (+ downstream)
  y  : lateral    (+ right)
  z  : vertical   (+ up)
  Body sits on floor z=0, centred at y=0, nose at x=0.

Usage
-----
    from openfoam.ahmed_case_generator import generate_ahmed_case

    generate_ahmed_case(
        case_dir   = "openfoam/cases/slant25",
        length_m   = 1.044,
        height_m   = 0.288,
        width_m    = 0.389,
        slant_deg  = 25.0,
        ground_clr = 0.050,
    )

Then in a terminal with OpenFOAM loaded:
    cd openfoam/cases/slant25
    blockMesh
    simpleFoam
    foamCalc mag U          # optional post-processing
"""

from __future__ import annotations

import json
import math
import os
from pathlib import Path
from typing import Optional


# ── Wind tunnel physics ────────────────────────────────────────────────────
U_INF    = 40.0        # m/s   freestream velocity
RHO      = 1.225       # kg/m³ air density at 20°C
NU       = 1.516e-5    # m²/s  kinematic viscosity at 20°C
A_SOUND  = 343.0       # m/s   speed of sound

# Turbulence inlet conditions (5% intensity, viscosity ratio 10)
TI       = 0.05
NU_RATIO = 10.0
K_INLET  = 1.5 * (U_INF * TI) ** 2
EPS_INF  = K_INLET * math.sqrt(K_INLET) * 0.09 ** 0.25   # estimate for omega inlet
OMEGA_INLET = math.sqrt(K_INLET) / (0.09 ** 0.25 * 0.001) if True else 100.0

# Frontal radius (standard AhmedML): rounded nose, fixed at ~100mm
NOSE_RADIUS_M = 0.100

# Side slant angle (fixed in standard Ahmed body)
SIDE_SLANT_DEG = 20.0

# Domain size multipliers (body-lengths)
DOMAIN_X_UPSTREAM  = 5.0   # lengths upstream of nose
DOMAIN_X_DOWNSTREAM= 12.0  # lengths downstream of base
DOMAIN_Y_HALF      = 5.0   # half-width
DOMAIN_Z_TOP       = 6.0   # heights above ground

_HEADER = """\
/*--------------------------------*- C++ -*----------------------------------*\\
| OpenFOAM Ahmed body case — generated by ParaKoop/openfoam/ahmed_case_generator.py |
\\*---------------------------------------------------------------------------*/
FoamFile
{{
    version     2.0;
    format      ascii;
    class       {cls};
    location    "{loc}";
    object      {obj};
}}
// * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * //
"""


def _header(cls: str, loc: str, obj: str) -> str:
    return _HEADER.format(cls=cls, loc=loc, obj=obj)


# ══════════════════════════════════════════════════════════════════════════
# Geometry helpers
# ══════════════════════════════════════════════════════════════════════════

def ahmed_body_points(L: float, H: float, W: float,
                      slant_deg: float, grnd: float,
                      nose_r: float = NOSE_RADIUS_M,
                      side_slant_deg: float = SIDE_SLANT_DEG) -> dict:
    """
    Returns key geometry dimensions of the Ahmed body in metres.

    Coordinate origin: front-bottom-centre (nose tip at (0, 0, grnd)).
    """
    slant_rad      = math.radians(slant_deg)
    side_slant_rad = math.radians(side_slant_deg)

    # Rear slant: projects backward and upward
    slant_h = H * math.sin(slant_rad)            # vertical drop of slant
    slant_x = slant_h / math.tan(slant_rad)      # = H * cos(slant_rad)
    slant_x = H * math.cos(slant_rad)

    # Side taper: the rear bottom corners taper inward
    side_inset = H * math.tan(side_slant_rad)    # lateral inset at rear base

    return {
        'L': L, 'H': H, 'W': W, 'grnd': grnd,
        'nose_r': nose_r, 'slant_deg': slant_deg,
        'slant_x': slant_x, 'slant_h': slant_h,
        'side_inset': side_inset,
        'body_top_z':  grnd + H,           # z at roof
        'body_base_z': grnd,               # z at underbody
        'base_x': L - slant_x,            # x where rear slant starts
        'slant_top_z': grnd + H,          # rear slant top (= roof height)
        'slant_bot_z': grnd + H - slant_h, # rear slant bottom
    }


def _re(L: float) -> float:
    return U_INF * L / NU


