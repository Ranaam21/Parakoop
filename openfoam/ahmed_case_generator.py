def _write_ahmed_stl(geo: dict, out_path: Path) -> None:
    """
    Generate a simplified Ahmed body STL (triangulated surfaces) in metres.

    This is an approximate geometry: straight sides with the slant at the
    correct angle. For high-fidelity runs, use CAD-generated STL.

    Surfaces: front_face, roof, underbody, rear_slant, rear_base,
              left_side, right_side + ground_clearance sides
    """
    L, H, W    = geo['L'], geo['H'], geo['W']
    grnd       = geo['ground_clr']
    slant_x    = geo['slant_x']
    slant_h    = geo['slant_h']
    body_top_z = grnd + H
    base_x     = L - slant_x   # x where rear slant starts
    side_in    = geo['side_inset']

    # Key x positions (all from nose)
    x_nose = 0.0
    x_cabin_start = 0.3 * L    # approximate cabin start (simplified)
    x_base  = base_x
    x_tail  = L

    # Half-width
    yw = W / 2.0

    triangles = []

    def tri(p1, p2, p3, normal=None):
        triangles.append((p1, p2, p3))

    def quad(p1, p2, p3, p4):
        # Two triangles from a quad (p1,p2,p3,p4 in order)
        tri(p1, p2, p3)
        tri(p1, p3, p4)

    # ── Underbody ────────────────────────────────────────────────────────
    quad((x_nose, -yw, grnd), (x_tail, -yw, grnd),
         (x_tail,  yw, grnd), (x_nose,  yw, grnd))

    # ── Roof ─────────────────────────────────────────────────────────────
    quad((x_nose, -yw, body_top_z), (x_base, -yw, body_top_z),
         (x_base,  yw, body_top_z), (x_nose,  yw, body_top_z))

    # ── Front face (vertical) ─────────────────────────────────────────────
    quad((x_nose, -yw, grnd), (x_nose,  yw, grnd),
         (x_nose,  yw, body_top_z), (x_nose, -yw, body_top_z))

    # ── Left side ─────────────────────────────────────────────────────────
    # Main body side (between nose and base)
    quad((x_nose, -yw, grnd), (x_nose, -yw, body_top_z),
         (x_base, -yw, body_top_z), (x_base, -yw, grnd))
    # Rear slant side (tapered by side_inset)
    z_slant_bot = body_top_z - slant_h
    quad((x_base, -yw, body_top_z), (x_tail, -(yw - side_in), z_slant_bot),
         (x_tail, -(yw - side_in), grnd), (x_base, -yw, grnd))

    # ── Right side (mirror) ───────────────────────────────────────────────
    quad((x_nose,  yw, grnd), (x_base,  yw, grnd),
         (x_base,  yw, body_top_z), (x_nose,  yw, body_top_z))
    quad((x_base,  yw, grnd), (x_tail,  (yw - side_in), grnd),
         (x_tail,  (yw - side_in), z_slant_bot), (x_base,  yw, body_top_z))

    # ── Rear slant ────────────────────────────────────────────────────────
    # From roof-base edge down to slant bottom
    quad((x_base, -yw, body_top_z), (x_base,  yw, body_top_z),
         (x_tail,  (yw - side_in), z_slant_bot),
         (x_tail, -(yw - side_in), z_slant_bot))

    # ── Rear base (vertical panel below slant bottom) ─────────────────────
    quad((x_tail, -(yw - side_in), grnd), (x_tail,  (yw - side_in), grnd),
         (x_tail,  (yw - side_in), z_slant_bot),
         (x_tail, -(yw - side_in), z_slant_bot))

    # ── Write ASCII STL ───────────────────────────────────────────────────
    lines = ["solid ahmed_body"]
    for p1, p2, p3 in triangles:
        # Compute face normal
        v1 = (p2[0]-p1[0], p2[1]-p1[1], p2[2]-p1[2])
        v2 = (p3[0]-p1[0], p3[1]-p1[1], p3[2]-p1[2])
        nx = v1[1]*v2[2] - v1[2]*v2[1]
        ny = v1[2]*v2[0] - v1[0]*v2[2]
        nz = v1[0]*v2[1] - v1[1]*v2[0]
        mag = math.sqrt(nx*nx + ny*ny + nz*nz) + 1e-15
        nx, ny, nz = nx/mag, ny/mag, nz/mag
        lines.append(f"  facet normal {nx:.6f} {ny:.6f} {nz:.6f}")
        lines.append("    outer loop")
        for p in (p1, p2, p3):
            lines.append(f"      vertex {p[0]:.6f} {p[1]:.6f} {p[2]:.6f}")
        lines.append("    endloop")
        lines.append("  endfacet")
    lines.append("endsolid ahmed_body")

    out_path.write_text("\n".join(lines))


