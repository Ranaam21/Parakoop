def _write_run_script(case_dir: Path, geo: dict) -> None:
    """Allrun shell script."""
    re = _re(geo['L'])
    content = f"""#!/bin/bash
# ParaKoop Ahmed body validation case
# Geometry: L={geo['L']*1000:.0f}mm H={geo['H']*1000:.0f}mm W={geo['W']*1000:.0f}mm
#           slant={geo['slant_deg']:.1f}° ground={geo['ground_clr']*1000:.0f}mm
# Flow:     U∞={U_INF}m/s  Re={re:.2e}  ν={NU:.3e}m²/s
# Solver:   simpleFoam k-ω SST

cd "$(dirname "$0")"

# 1. Mesh the outer domain
blockMesh 2>&1 | tee log.blockMesh

# 2. Copy STL to constant/triSurface (generate ahmed_body.stl first)
mkdir -p constant/triSurface
[ -f ahmed_body.stl ] && cp ahmed_body.stl constant/triSurface/ || \\
    echo "WARNING: ahmed_body.stl not found — generate with generate_ahmed_stl.py first"

# 3. Surface feature extraction + snappy meshing
surfaceFeatureExtract  2>&1 | tee log.surfaceFeatureExtract
snappyHexMesh -overwrite 2>&1 | tee log.snappyHexMesh

# 4. Run simpleFoam
simpleFoam 2>&1 | tee log.simpleFoam

# 5. Extract Cd/Cl from force coefficients
grep "Cd" postProcessing/forceCoeffs/0/forceCoeffs.dat | tail -5
echo "---"
echo "ParaKoop predicted Cd: {geo.get('pk_cd_pred', 'N/A')}  Cl: {geo.get('pk_cl_pred', 'N/A')}"
"""
    (case_dir / 'Allrun').write_text(content)
    (case_dir / 'Allrun').chmod(0o755)


