def _write_block_mesh_dict(geo: dict, out_dir: Path) -> None:
    """
    blockMeshDict for the outer wind-tunnel domain.
    Mesh cells: uniform hex with ~50mm base cell size.
    Refinement done in snappyHexMesh (see snappy_hex_mesh_dict).
    """
    L = geo['L']
    x0 = -DOMAIN_X_UPSTREAM  * L
    x1 =  DOMAIN_X_DOWNSTREAM * L
    y0 = -DOMAIN_Y_HALF      * geo['W'] / 2
    y1 =  DOMAIN_Y_HALF      * geo['W'] / 2
    z0 =  0.0
    z1 =  DOMAIN_Z_TOP       * geo['H']

    dx, dy, dz = (x1 - x0), (y1 - y0), z1
    nx = max(20, int(dx / (L / 10)))
    ny = max(10, int(dy / (geo['W'] / 5)))
    nz = max(10, int(dz / (geo['H'] / 4)))

    content = _header('dictionary', 'constant/polyMesh', 'blockMeshDict') + f"""
scale 1.0;

vertices
(
    ({x0:.4f} {y0:.4f} {z0:.4f})  // 0
    ({x1:.4f} {y0:.4f} {z0:.4f})  // 1
    ({x1:.4f} {y1:.4f} {z0:.4f})  // 2
    ({x0:.4f} {y1:.4f} {z0:.4f})  // 3
    ({x0:.4f} {y0:.4f} {z1:.4f})  // 4
    ({x1:.4f} {y0:.4f} {z1:.4f})  // 5
    ({x1:.4f} {y1:.4f} {z1:.4f})  // 6
    ({x0:.4f} {y1:.4f} {z1:.4f})  // 7
);

blocks
(
    hex (0 1 2 3 4 5 6 7)
    ({nx} {ny} {nz})
    simpleGrading (1 1 1)
);

boundary
(
    inlet
    {{
        type patch;
        faces ((0 4 7 3));
    }}
    outlet
    {{
        type patch;
        faces ((1 2 6 5));
    }}
    top
    {{
        type symmetryPlane;
        faces ((4 5 6 7));
    }}
    sides
    {{
        type symmetryPlane;
        faces ((0 1 5 4) (3 7 6 2));
    }}
    ground
    {{
        type wall;
        faces ((0 3 2 1));
    }}
);
"""
    (out_dir / 'constant' / 'polyMesh' / 'blockMeshDict').write_text(content)


def _write_snappy_hex_mesh(geo: dict, out_dir: Path) -> None:
    """
    snappyHexMeshDict — refines the mesh around and inside the Ahmed body.
    Assumes ahmed_body.stl is in constant/triSurface/.
    """
    content = _header('dictionary', 'system', 'snappyHexMeshDict') + """
castellatedMesh true;
snap            true;
addLayers       true;

mergeTolerance  1e-6;

geometry
{
    ahmed_body
    {
        type triSurfaceMesh;
        file "ahmed_body.stl";
    }
    refinementBox
    {
        type searchableBox;
        min  (-0.1 -0.3 0.0);
        max  ( 2.5  0.3 0.5);
    }
}

castellatedMeshControls
{
    maxLocalCells        1000000;
    maxGlobalCells       5000000;
    minRefinementCells   10;
    nCellsBetweenLevels  3;

    features ( );

    refinementSurfaces
    {
        ahmed_body
        {
            level (3 4);
            patchInfo { type wall; }
        }
    }

    refinementRegions
    {
        refinementBox { mode inside; levels ((1 1)); }
        ahmed_body    { mode distance; levels ((0.05 3) (0.15 2) (0.5 1)); }
    }

    resolveFeatureAngle 30;
    locationInMesh (""" + f"{-geo['L']*0.5:.4f} 0.05 {geo['H']*0.5 + 0.05:.4f}" + """);  // offset from cell faces
    allowFreeStandingZoneFaces true;
}

snapControls
{
    nSmoothPatch    3;
    tolerance       2.0;
    nSolveIter      30;
    nRelaxIter      5;
}

addLayersControls
{
    relativeSizes       true;
    layers
    {
        ahmed_body { nSurfaceLayers 5; }
        ground     { nSurfaceLayers 3; }
    }
    expansionRatio          1.2;
    finalLayerThickness     0.3;
    minThickness            0.1;
    nGrow                   0;
    featureAngle            60;
    nRelaxIter              3;
    nSmoothSurfaceNormals   1;
    nSmoothNormals          3;
    nSmoothThickness        10;
    maxFaceThicknessRatio   0.5;
    maxThicknessToMedialRatio 0.3;
    minMedialAxisAngle      90;
    nBufferCellsNoExtrude   0;
    nLayerIter              50;
}

meshQualityControls
{
    maxNonOrtho         65;
    maxBoundarySkewness 20;
    maxInternalSkewness 4;
    maxConcave          80;
    minFlatness         0.5;
    minVol              1e-13;
    minTetQuality       1e-30;
    minArea             -1;
    minTwist            0.02;
    minDeterminant      0.001;
    minFaceWeight       0.05;
    minVolRatio         0.01;
    minTriangleTwist    -1;
    nSmoothScale        4;
    errorReduction      0.75;
}
"""
    (out_dir / 'system' / 'snappyHexMeshDict').write_text(content)


