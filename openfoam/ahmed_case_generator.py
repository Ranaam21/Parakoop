def generate_ahmed_case(
    case_dir:    str,
    length_m:    float,
    height_m:    float,
    width_m:     float,
    slant_deg:   float,
    ground_clr:  float = 0.050,
    n_iter:      int   = 1000,
    n_procs:     int   = 4,
    pk_cd_pred:  Optional[float] = None,
    pk_cl_pred:  Optional[float] = None,
) -> dict:
    """
    Write a complete OpenFOAM simpleFoam case for an Ahmed body.

    Parameters
    ----------
    case_dir   : output directory (created if needed)
    length_m   : body length in metres
    height_m   : body height in metres (ground clearance not included)
    width_m    : body width in metres
    slant_deg  : rear slant angle in degrees
    ground_clr : ground clearance in metres (default 50mm = 0.050)
    n_iter     : number of simpleFoam iterations (default 1000)
    n_procs    : MPI decomposition processors (default 4)
    pk_cd_pred : ParaKoop predicted Cd (annotated in Allrun script)
    pk_cl_pred : ParaKoop predicted Cl (annotated in Allrun script)

    Returns
    -------
    dict with geometry summary and file paths written
    """
    out = Path(case_dir)
    (out / '0').mkdir(parents=True, exist_ok=True)
    (out / 'constant' / 'polyMesh').mkdir(parents=True, exist_ok=True)
    (out / 'constant' / 'triSurface').mkdir(parents=True, exist_ok=True)
    (out / 'system').mkdir(parents=True, exist_ok=True)

    geo = ahmed_body_points(length_m, height_m, width_m, slant_deg, ground_clr)
    geo['ground_clr'] = ground_clr
    if pk_cd_pred is not None:
        geo['pk_cd_pred'] = pk_cd_pred
    if pk_cl_pred is not None:
        geo['pk_cl_pred'] = pk_cl_pred

    # Write all OpenFOAM dictionaries
    _write_block_mesh_dict(geo, out)
    _write_snappy_hex_mesh(geo, out)
    _write_U(geo, out)
    _write_p(out)
    _write_nut(out)
    _write_k(out)
    _write_omega(out)
    _write_transport_properties(out)
    _write_turbulence_properties(out)
    _write_control_dict(geo, out, n_iter)
    _write_fv_schemes(out)
    _write_fv_solution(out)
    _write_decompose_par(out, n_procs)
    _write_surface_feature_dict(out)

    # Generate Ahmed body STL
    stl_path = out / 'constant' / 'triSurface' / 'ahmed_body.stl'
    _write_ahmed_stl(geo, stl_path)

    # Write Allrun script
    _write_run_script(out, geo)

    # Write geometry summary JSON
    summary = {
        'length_mm':  length_m * 1000,
        'height_mm':  height_m * 1000,
        'width_mm':   width_m  * 1000,
        'slant_deg':  slant_deg,
        'ground_clr_mm': ground_clr * 1000,
        'Re':         _re(length_m),
        'U_inf_ms':   U_INF,
        'frontal_area_m2': height_m * width_m,
        'pk_cd_pred': pk_cd_pred,
        'pk_cl_pred': pk_cl_pred,
    }
    (out / 'parakoop_geometry.json').write_text(json.dumps(summary, indent=2))

    return {'case_dir': str(out), 'geo': geo, 'files_written': sorted(str(p) for p in out.rglob('*') if p.is_file())}


def generate_cases_from_inverse_design(
    results_json:  str,
    output_dir:    str = 'openfoam/cases',
    ref_length_m:  float = 0.900,
    ref_height_m:  float = 0.288,
    ref_width_m:   float = 0.389,
    ground_clr_m:  float = 0.050,
) -> list:
    """
    Generate OpenFOAM cases from inverse_suggest.py JSON output.

    Parameters
    ----------
    results_json : path to JSON saved by `inverse_suggest.py --json <path>`
    output_dir   : base directory for cases
    ref_length_m : reference body length in metres (AhmedML default ≈ 0.9m)
    ref_height_m : reference body height in metres (AhmedML default ≈ 0.288m)
    ref_width_m  : reference body width in metres  (AhmedML default ≈ 0.389m)

    Returns
    -------
    list of case directories written
    """
    with open(results_json) as f:
        results = json.load(f)

    if isinstance(results, dict):
        results = [results]

    cases = []
    for i, r in enumerate(results):
        ep = r.get('end_params', {})
        # Scale: use slant_deg from end_params if available
        slant_deg = ep.get('rear_slant_deg', 25.0)
        h_mm = ep.get('height_mm', ref_height_m * 1000)
        w_mm = ep.get('width_mm',  ref_width_m  * 1000)

        # Scale to AhmedML reference length (keep ratios)
        # end_params give DrivAerNet-scale mm; rescale by h_l_ratio
        theta_end = r.get('theta_end', [])
        if len(theta_end) >= 4:
            h_l_ratio = theta_end[3]
            h_m   = h_l_ratio * ref_length_m
            w_h_ratio = theta_end[4] if len(theta_end) >= 5 else 1.35
            w_m   = w_h_ratio * h_m
        else:
            h_m = ref_height_m
            w_m = ref_width_m

        label    = f"slant{slant_deg:.0f}_case{i+1:02d}"
        case_dir = os.path.join(output_dir, label)
        info     = generate_ahmed_case(
            case_dir   = case_dir,
            length_m   = ref_length_m,
            height_m   = h_m,
            width_m    = w_m,
            slant_deg  = slant_deg,
            ground_clr = ground_clr_m,
            pk_cd_pred = r.get('achieved_cd'),
            pk_cl_pred = r.get('achieved_cl'),
        )
        cases.append(case_dir)
        print(f"  [{i+1}] {label}  L={ref_length_m*1000:.0f}mm h={h_m*1000:.0f}mm "
              f"slant={slant_deg:.1f}°  → {case_dir}")

    return cases


